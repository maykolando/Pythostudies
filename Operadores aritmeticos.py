"""
+ adição
- subtração
* multiplicar
/ dividir
// divisão inteira
% resto da divisao
** eleva potência
"""
n1 = 10
n2 = 3

adicao = n1 + n2

print ("resultado da soma ", adicao)

subtracao = n1 - n2
print ("Resultado subtração ", subtracao)

multiplicacao = n1 * n2
print ("Resultado multiplicacao ", multiplicacao)

divisao = n1 / n2
print ("Resultado divisao ", divisao)

divisaoInteira = n1 // n2
print ("Resultado divisao inteira ", divisaoInteira)

modulo = n1 % n2
print ("Resultado modulo ", modulo)

potencia = n1 ** n2
print ("Resultado potencia ", potencia)